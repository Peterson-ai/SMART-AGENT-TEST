    kb_input = st.text_area("Documents (One per line)", value=default_text, height=300)

    # Button to rebuild index
    if st.button("🔄 Rebuild Brain (Index)", type="primary"):
        with st.spinner("Indexing documents..."):
            documents = [line.strip() for line in kb_input.split('\n') if line.strip()]

            if documents:
                # Create Embeddings
                embeddings = embedding_model.encode(documents)
                dimension = embeddings.shape[1]

                # Create FAISS Index
                index = faiss.IndexFlatL2(dimension)
                index.add(np.array(embeddings))

                # Save to session state
                st.session_state['index'] = index
                st.session_state['documents'] = documents
                st.success(f"Indexed {len(documents)} documents!")
            else:
                st.error("Knowledge base is empty.")


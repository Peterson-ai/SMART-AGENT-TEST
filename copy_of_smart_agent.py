# --- 4. SEARCH & GENERATION FUNCTIONS ---

def retrieve_docs(query, k=2):
    if 'index' not in st.session_state:
        return []

    query_vec = embedding_model.encode([query])
    distances, idx = st.session_state['index'].search(np.array(query_vec), k)

    # Handle case where index might be empty or invalid
    results = []
    for i in idx[0]:
        if 0 <= i < len(st.session_state['documents']):
            results.append(st.session_state['documents'][i])
    return results

def generate_answers(query, retrieved_context):
    context_str = "\n".join(retrieved_context)

    # 1. RAG Prompt
    rag_prompt = f"""
    You are a helpful teaching assistant.
    Use ONLY the context below to answer the question. If the answer isn't in the context, say "I don't know based on the provided documents."

    Context:
    {context_str}

    Question: {query}
    """

    # 2. Pure GPT Prompt (for comparison)
    base_prompt = f"Answer the following question to the best of your ability: {query}"

    rag_response = "Error: Client not initialized"
    base_response = "Error: Client not initialized"

    if client:
        # Get RAG Answer
        r1 = client.chat.completions.create(
            model="gpt-4o-mini",
            messages=[{"role": "user", "content": rag_prompt}],
            temperature=0.3
        )
        rag_response = r1.choices[0].message.content

        # Get Base Answer
        r2 = client.chat.completions.create(
            model="gpt-4o-mini",
            messages=[{"role": "user", "content": base_prompt}],
            temperature=0.3
        )
        base_response = r2.choices[0].message.content

    return rag_response, base_response

# --- 5. CHAT INPUT HANDLER ---
if prompt := st.chat_input():
    if not client:
        st.error("Please enter your API Key in the sidebar first.")
    elif 'index' not in st.session_state:
        st.error("Please click 'Build Brain (Index)' in the sidebar first.")
    else:
        # User Message
        st.session_state.messages.append({"role": "user", "content": prompt})
        st.chat_message("user").write(prompt)

        # Processing
        with st.spinner("Thinking..."):
            # 1. Retrieve
            retrieved_docs = retrieve_docs(prompt)

            # 2. Generate
            rag_ans, base_ans = generate_answers(prompt, retrieved_docs)

            # 3. Format Output

            # Create a visual container for the answer
            with st.chat_message("assistant"):

                # A. Show what the AI "read" (The Retrieval Part)
                with st.expander("🔍 **Step 1: Retrieval (What I read)**", expanded=False):
                    if retrieved_docs:
                        for idx, doc in enumerate(retrieved_docs):
                            st.info(f"**Doc {idx+1}:** {doc}")
                    else:
                        st.warning("No relevant documents found.")

                # B. Side-by-Side Comparison
                st.markdown("#### **Step 2: Answer Comparison**")
                col1, col2 = st.columns(2)

                with col1:
                    st.success("**✅ RAG Agent (Context-Aware)**")
                    st.write(rag_ans)

                with col2:
                    st.warning("**🤖 Standard GPT (General Knowledge)**")
                    st.write(base_ans)

            # Save assistant response to history (we only save the RAG answer text for simplicity in history)
            st.session_state.messages.append({"role": "assistant", "content": rag_ans})